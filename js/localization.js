export function applyLanguage() {
document.documentElement.lang = getLang();
const set = (id, txt) => { const el = document.getElementById(id); if (el) el.textContent = txt; };
set('coverSub', t('cover.subtitle'));
set('btn-start', t('cover.start'));
set('distanceLabel', t('hud.distance'));
set('levelLabel', t('hud.level'));
set('healthBarLabel', t('hud.health'));
set('btn-stats', t('hud.stats'));
set('btn-settings', t('hud.settings'));
set('btn-shop', t('hud.shop'));
const tray = document.querySelector('.tray-title'); if (tray) tray.textContent = t('hud.tray');
const langTitle = document.querySelector('.lang-title');
if (langTitle) langTitle.textContent = t('cover.langTitle');
set('btn-rebirth', t('rebirth.btn'));
const rbTitle = document.querySelector('#rebirth-overlay .rebirth-title');
if (rbTitle) rbTitle.textContent = t('rebirth.tree');
set('rebirth-close', t('rebirth.close'));
Bus.emit('langChanged');
}